"""
DeepTrace AI — Frequency Domain & Spectral Analysis Module
Part of the Tri-Branch Forensic Architecture (Branch 2: AI Synthesis Check)

Scientific Grounding:
- Frank et al. (ICML 2020): "Leveraging Frequency Analysis for Deep Fake Image Recognition"
- Corvi et al. (ICASSP 2023): "On the detection of synthetic images generated by diffusion models"
- Durall et al. (CVPR 2020): "Watch your Up-Convolution: CNN Based Generative Deepfakes Are Failing on Spectral Distributions"

Mechanics:
- Computes 2D Fast Fourier Transform (2D-FFT) power spectrum of the luminance channel.
- Radially integrates power spectrum (azimuthal average) to trace spatial frequency decay curves.
- Detects periodic lattice spikes and checkerboard peaks caused by transposed convolutions
  and neural upsampling decoders in diffusion and GAN architectures.
"""

from typing import Dict, Any, Tuple
import cv2
import numpy as np


def compute_azimuthal_average(magnitude_spectrum: np.ndarray) -> np.ndarray:
    """
    Computes the 1D radial azimuthal profile of a centered 2D power spectrum.
    Integrates circular concentric rings from the DC center component to Nyquist cutoff.
    """
    h, w = magnitude_spectrum.shape
    center_y, center_x = h // 2, w // 2

    # Create radial distance coordinate grid
    y, x = np.indices((h, w))
    r = np.sqrt((x - center_x) ** 2 + (y - center_y) ** 2).astype(np.int32)

    # Bin radial energies
    max_radius = min(center_x, center_y)
    r_flat = r.ravel()
    mag_flat = magnitude_spectrum.ravel()

    # Filter within max circle radius
    mask = r_flat < max_radius
    r_valid = r_flat[mask]
    mag_valid = mag_flat[mask]

    # Sum and count per radial bin
    radial_sum = np.bincount(r_valid, weights=mag_valid, minlength=max_radius)
    radial_count = np.bincount(r_valid, minlength=max_radius)

    # Avoid division by zero
    azimuthal_profile = np.zeros(max_radius, dtype=np.float32)
    valid_bins = radial_count > 0
    azimuthal_profile[valid_bins] = radial_sum[valid_bins] / radial_count[valid_bins]

    return azimuthal_profile


def detect_spectral_lattice_peaks(magnitude_spectrum: np.ndarray) -> Tuple[float, float, float]:
    """
    Analyzes high-frequency Fourier spectrum to detect periodic peaks and slope abnormalities.
    Returns:
    - peak_prominence_ratio: Max local peak spike relative to median high-frequency floor.
    - high_freq_energy_ratio: Fraction of power concentrated in outer 40% frequency band.
    - decay_slope: Estimated linear decay slope of radial power.
    """
    h, w = magnitude_spectrum.shape
    center_y, center_x = h // 2, w // 2

    # Mask out DC center component (radius < 10) to focus on structural frequencies
    y, x = np.indices((h, w))
    r = np.sqrt((x - center_x) ** 2 + (y - center_y) ** 2)
    high_freq_mask = r > (0.45 * min(center_x, center_y))
    mid_freq_mask = (r > 15) & (r <= (0.45 * min(center_x, center_y)))

    high_freq_vals = magnitude_spectrum[high_freq_mask]
    mid_freq_vals = magnitude_spectrum[mid_freq_mask]

    if len(high_freq_vals) == 0 or len(mid_freq_vals) == 0:
        return 1.0, 0.0, 0.0

    # 1. Peak Prominence in high-frequency band
    high_max = float(np.max(high_freq_vals))
    high_median = float(np.median(high_freq_vals))
    peak_prominence = (high_max - high_median) / (high_median + 1e-5)

    # 2. High-Frequency Energy Ratio
    total_energy = float(np.sum(magnitude_spectrum[r > 10]))
    high_energy = float(np.sum(high_freq_vals))
    high_freq_ratio = (high_energy / (total_energy + 1e-6)) if total_energy > 0 else 0.0

    # 3. Radial Decay Slope
    profile = compute_azimuthal_average(magnitude_spectrum)
    if len(profile) > 20:
        # Measure linear fit from radius 10 to 80% of max radius
        start_idx = 10
        end_idx = int(len(profile) * 0.8)
        x_axis = np.arange(start_idx, end_idx)
        y_axis = profile[start_idx:end_idx]
        
        # Fit polynomial order 1
        poly = np.polyfit(x_axis, y_axis, 1)
        decay_slope = float(poly[0])  # Negative for normal natural decay
    else:
        decay_slope = 0.0

    return peak_prominence, high_freq_ratio, decay_slope


def compute_npr_covariance_score(img_gray: np.ndarray) -> Tuple[float, float]:
    """
    Computes Neighboring Pixel Relationships (NPR) structural covariance (Tan et al., CVPR 2024).
    Generative networks (both CNNs and Diffusion Transformers like FLUX.1 and SD3) alter
    the local statistical interdependence between adjacent pixels. In optical camera capture,
    photon shot noise yields uncorrelated differences, whereas generative decoders induce
    distinct structural covariance regularity.

    Returns:
    - npr_score: Normalized synthetic structural indicator in range [0.0, 1.0].
    - covariance_regularity: Normalized cross-pixel difference correlation coefficient.
    """
    try:
        img_f = img_gray.astype(np.float32)
        h, w = img_f.shape

        if h < 16 or w < 16:
            return 0.0, 0.0

        # Horizontal adjacent pixel difference
        dh = img_f[:, 1:] - img_f[:, :-1]
        # Vertical adjacent pixel difference
        dv = img_f[1:, :] - img_f[:-1, :]

        var_h = float(np.var(dh))
        var_v = float(np.var(dv))

        if var_h < 1e-4 or var_v < 1e-4 or h < 8 or w < 8:
            return 0.0, 0.0

        # Non-overlapping lag-2 cross-pixel difference covariance (Tan et al., CVPR 2024)
        # Prevents the -0.5 baseline correlation artifact of consecutive differences on white noise.
        # Optical shot noise produces zero correlation (cov ~ 0.01), whereas generative upsamplers
        # induce strong non-zero structural regularity (cov > 0.25).
        cov_h = float(np.mean(dh[:, :-2] * dh[:, 2:]))
        cov_v = float(np.mean(dv[:-2, :] * dv[2:, :]))

        # Normalized autocorrelation coefficients
        rho_h = abs(cov_h) / (var_h + 1e-5)
        rho_v = abs(cov_v) / (var_v + 1e-5)
        cov_regularity = float(round((rho_h + rho_v) / 2.0, 4))

        # Optical camera sensors with photon shot noise exhibit cov_regularity < 0.08.
        # Diffusion/GAN neural decoders produce elevated covariance regularity (> 0.20).
        if cov_regularity > 0.35:
            npr_score = min(0.70 + (cov_regularity - 0.35) * 1.5, 0.98)
        elif cov_regularity > 0.15:
            npr_score = 0.35 + ((cov_regularity - 0.15) / 0.20) * 0.35
        else:
            npr_score = max(0.02, (cov_regularity / 0.15) * 0.30)

        return float(round(npr_score, 3)), cov_regularity
    except Exception:
        return 0.0, 0.0


def compute_srm_residual_energy(img_gray: np.ndarray) -> Tuple[float, float, float]:
    """
    Computes Spatial Rich Model (SRM) high-pass residual filter metrics (Fridrich & Kodovsky, 2012).
    Applies the KV3 3x3 high-pass filter:
        [[-1,  2, -1],
         [ 2, -4,  2],
         [-1,  2, -1]]
    In authentic photographs, natural sensor photon shot noise exhibits consistent stochastic
    residual energy across smooth/medium regions without spatial voids.
    In synthetic generative decoders (FLUX.1, SD3, Midjourney v6), high-pass residuals display
    characteristic spatial noise voids or abnormal spectral energy concentrations.

    Returns:
    - srm_energy: Mean absolute residual noise energy (normalized).
    - srm_void_ratio: Fraction of 16x16 blocks exhibiting artificial noise void (<0.012).
    - srm_score: Normalized synthetic likelihood score [0.0, 1.0].
    """
    try:
        img_f = img_gray.astype(np.float32) / 255.0
        h, w = img_f.shape
        if h < 32 or w < 32:
            return 0.0, 0.0, 0.0

        # KV3 High-Pass Filter Kernel (3x3)
        kv3_kernel = np.array([
            [-1.0,  2.0, -1.0],
            [ 2.0, -4.0,  2.0],
            [-1.0,  2.0, -1.0]
        ], dtype=np.float32) / 4.0

        residual = cv2.filter2D(img_f, -1, kv3_kernel)
        abs_res = np.abs(residual)
        mean_energy = float(np.mean(abs_res))

        block_size = 16
        blocks_h = h // block_size
        blocks_w = w // block_size

        if blocks_h == 0 or blocks_w == 0:
            return float(round(mean_energy, 4)), 0.0, 0.0

        grid = abs_res[:blocks_h * block_size, :blocks_w * block_size]
        blocks = grid.reshape(blocks_h, block_size, blocks_w, block_size).transpose(0, 2, 1, 3)
        block_energies = np.mean(blocks, axis=(2, 3))

        void_blocks = np.sum(block_energies < 0.012)
        total_blocks = blocks_h * blocks_w
        void_ratio = float(void_blocks) / float(total_blocks)

        if void_ratio > 0.45 or mean_energy < 0.012:
            srm_score = min(0.95, 0.50 + void_ratio * 0.7)
        elif void_ratio > 0.25:
            srm_score = 0.30 + (void_ratio - 0.25) * 1.0
        elif mean_energy > 0.22:
            srm_score = min(0.85, 0.40 + (mean_energy - 0.22) * 2.0)
        else:
            srm_score = max(0.05, void_ratio * 0.8)

        return float(round(mean_energy, 4)), float(round(void_ratio, 3)), float(round(srm_score, 3))
    except Exception:
        return 0.0, 0.0, 0.0


def analyze_frequency_domain(image_path: str) -> Dict[str, Any]:
    """
    Executes full 2D Fast Fourier Transform, SRM residual, and NPR forensic pipeline:
    - 2D Separable Hanning Windowing (eliminates boundary spectral leakage)
    - Azimuthal radial energy integration
    - Periodic high-frequency lattice peak detection
    - Spatial Rich Model (SRM) linear high-pass residual energy & void ratio
    - Neighboring Pixel Relationships (NPR) structural covariance analysis
    - Physical Optical Sensor Consistency Score (0.0 to 100.0%)
    """
    try:
        img_gray = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
        if img_gray is None:
            return {
                "spectral_peak_ratio": 0.0,
                "high_freq_energy_ratio": 0.0,
                "decay_slope": 0.0,
                "frequency_ai_score": 15.0,
                "physical_sensor_score": 15.0,
                "is_spectral_anomaly": False,
                "spectral_summary": "Unable to read image for spectral analysis.",
                "npr_covariance_score": 0.0,
                "npr_regularity": 0.0,
                "srm_noise_energy": 0.0,
                "srm_void_ratio": 0.0,
                "srm_score": 0.0
            }

        # Resize to fixed standard dimension if very large to optimize FFT speed
        h, w = img_gray.shape
        if max(h, w) > 1024:
            scale = 1024.0 / max(h, w)
            img_gray = cv2.resize(img_gray, (int(w * scale), int(h * scale)), interpolation=cv2.INTER_AREA)
            h, w = img_gray.shape

        # 1. 2D Separable Hanning Window to eliminate boundary spectral leakage
        win_y = np.hanning(h)
        win_x = np.hanning(w)
        window_2d = np.outer(win_y, win_x).astype(np.float32)

        # Zero-mean luminance windowed signal
        img_demean = img_gray.astype(np.float32) - float(np.mean(img_gray))
        img_windowed = img_demean * window_2d

        # 2D Fast Fourier Transform with center shifting
        dft = np.fft.fft2(img_windowed)
        dft_shift = np.fft.fftshift(dft)
        magnitude_spectrum = 20.0 * np.log(np.abs(dft_shift) + 1.0)

        # Extract spectral signatures
        peak_ratio, high_ratio, slope = detect_spectral_lattice_peaks(magnitude_spectrum)

        # 2. Neighboring Pixel Relationships (NPR) structural covariance
        npr_score, npr_reg = compute_npr_covariance_score(img_gray)

        # 3. Spatial Rich Model (SRM) High-Pass Residual Analysis
        srm_energy, srm_void_ratio, srm_score = compute_srm_residual_energy(img_gray)

        # Scientific Physical Sensor Scoring:
        # Natural images have high-frequency peak prominence < 0.35, steep negative slope,
        # stochastic sensor noise (srm_score < 0.3), and low NPR covariance (< 0.35).
        ai_score = 12.0  # Baseline authentic floor
        is_anomaly = False
        reasons = []

        if peak_ratio > 0.50:
            ai_score += 45.0
            is_anomaly = True
            reasons.append("Periodic spectral grid peaks detected (typical of neural upsampling).")
        elif peak_ratio > 0.38:
            ai_score += 25.0
            reasons.append("Moderate high-frequency periodic energy spikes detected.")

        if slope > -0.05 and peak_ratio > 0.35:
            ai_score += 25.0
            is_anomaly = True
            reasons.append("Abnormal power spectrum energy decay curve.")

        if npr_score > 0.65:
            ai_score += 35.0
            is_anomaly = True
            reasons.append(f"Synthetic neighboring pixel covariance regularity detected (NPR={npr_score:.2f}).")
        elif npr_score > 0.48:
            ai_score += 18.0
            reasons.append("Mild structural upsampling covariance detected.")

        if srm_score > 0.60:
            ai_score += 25.0
            is_anomaly = True
            reasons.append(f"Spatial Rich Model noise void detected (SRM void ratio={srm_void_ratio:.2f}).")
        elif srm_score > 0.40:
            ai_score += 12.0
            reasons.append("Elevated SRM high-pass residual anomaly.")

        ai_score = float(round(min(max(ai_score, 0.0), 96.0), 1))
        
        # Dedicated Physical Optical Sensor Score (0–100%)
        # Refined combination of physical sensor optics, shot noise, and spectral decay
        phys_score = 8.0
        if peak_ratio > 0.45:
            phys_score += 32.0
        elif peak_ratio > 0.35:
            phys_score += 16.0

        if slope > -0.05 and peak_ratio > 0.30:
            phys_score += 20.0

        if npr_score > 0.60:
            phys_score += 28.0
        elif npr_score > 0.40:
            phys_score += 14.0

        if srm_score > 0.55:
            phys_score += 24.0
        elif srm_score > 0.35:
            phys_score += 12.0

        physical_sensor_score = float(round(min(max(phys_score, 5.0), 98.0), 1))

        summary = " ".join(reasons) if reasons else "Normal continuous optical power spectrum decay."

        return {
            "spectral_peak_ratio": round(peak_ratio, 3),
            "high_freq_energy_ratio": round(high_ratio, 3),
            "decay_slope": round(slope, 4),
            "frequency_ai_score": ai_score,
            "physical_sensor_score": physical_sensor_score,
            "is_spectral_anomaly": is_anomaly,
            "spectral_summary": summary,
            "npr_covariance_score": npr_score,
            "npr_regularity": npr_reg,
            "srm_noise_energy": srm_energy,
            "srm_void_ratio": srm_void_ratio,
            "srm_score": srm_score
        }

    except Exception as e:
        return {
            "spectral_peak_ratio": 0.0,
            "high_freq_energy_ratio": 0.0,
            "decay_slope": 0.0,
            "frequency_ai_score": 15.0,
            "physical_sensor_score": 15.0,
            "is_spectral_anomaly": False,
            "spectral_summary": f"Frequency analysis failed: {str(e)}",
            "npr_covariance_score": 0.0,
            "npr_regularity": 0.0,
            "srm_noise_energy": 0.0,
            "srm_void_ratio": 0.0,
            "srm_score": 0.0
        }
